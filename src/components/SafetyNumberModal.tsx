import React, { useState, useEffect } from 'react';
import { X, ShieldCheck, ShieldAlert, KeyRound, Copy, Check } from 'lucide-react';
import { UserProfile, SafetyNumberInfo } from '../types/crypto';
import { getSafetyNumberInfo, setContactVerification } from '../services/storage';

interface SafetyNumberModalProps {
  currentUser: UserProfile;
  peerUser: UserProfile;
  onClose: () => void;
  onVerificationChanged: () => void;
}

export const SafetyNumberModal: React.FC<SafetyNumberModalProps> = ({
  currentUser,
  peerUser,
  onClose,
  onVerificationChanged,
}) => {
  const [safetyInfo, setSafetyInfo] = useState<SafetyNumberInfo | null>(null);
  const [isCopied, setIsCopied] = useState(false);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let isMounted = true;
    getSafetyNumberInfo(currentUser.id, peerUser.id).then((info) => {
      if (isMounted) {
        setSafetyInfo(info);
        setLoading(false);
      }
    });
    return () => {
      isMounted = false;
    };
  }, [currentUser.id, peerUser.id]);

  const handleToggleVerified = () => {
    if (!safetyInfo) return;
    const nextState = !safetyInfo.isVerified;
    setContactVerification(currentUser.id, peerUser.id, nextState);
    setSafetyInfo({
      ...safetyInfo,
      isVerified: nextState,
    });
    onVerificationChanged();
  };

  const handleCopy = () => {
    if (!safetyInfo) return;
    navigator.clipboard.writeText(safetyInfo.combinedSafetyNumber);
    setIsCopied(true);
    setTimeout(() => setIsCopied(false), 2000);
  };

  const chunks = safetyInfo ? safetyInfo.combinedSafetyNumber.split(' ') : [];

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-xs">
      <div className="bg-slate-900 border border-slate-800 rounded-xl max-w-xl w-full flex flex-col shadow-2xl">
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-800 flex items-center justify-between shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center text-emerald-400">
              <KeyRound className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-white">
                Verify Safety Numbers (MITM Protection)
              </h3>
              <p className="text-xs text-slate-400">
                End-to-end cryptographic fingerprint for {peerUser.displayName}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6 space-y-6 text-xs overflow-y-auto">
          {/* Explanation */}
          <div className="bg-slate-950 p-3.5 rounded-lg border border-slate-800 text-slate-300 leading-relaxed">
            Safety numbers are generated by hashing both parties&apos; ECDH public keys.
            Compare these numbers with <strong className="text-white">{peerUser.displayName}</strong> over an
            in-person or trusted out-of-band channel to guarantee that no third party (such as a rogue proxy or ISP)
            is intercepting your communication.
          </div>

          {loading ? (
            <div className="py-8 text-center text-slate-500 font-mono">
              Computing SHA-256 canonical safety numbers...
            </div>
          ) : (
            <>
              {/* Visual Numeric Blocks (Signal 12-block style) */}
              <div className="space-y-2">
                <div className="flex items-center justify-between text-slate-400 font-medium">
                  <span>60-Digit Cryptographic Safety Number</span>
                  <button
                    onClick={handleCopy}
                    className="flex items-center gap-1 text-emerald-400 hover:text-emerald-300 transition-colors"
                  >
                    {isCopied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                    <span>{isCopied ? 'Copied' : 'Copy Numbers'}</span>
                  </button>
                </div>

                <div className="grid grid-cols-3 sm:grid-cols-4 gap-2 bg-slate-950 p-4 rounded-lg border border-slate-800">
                  {chunks.map((chunk, idx) => (
                    <div
                      key={idx}
                      className="bg-slate-900 border border-slate-800/80 p-2.5 rounded text-center font-mono text-sm tracking-wider font-semibold text-emerald-400 tabular-nums shadow-xs"
                    >
                      {chunk}
                    </div>
                  ))}
                </div>
              </div>

              {/* Public Key Fingerprints */}
              <div className="space-y-2">
                <div className="text-slate-400 font-medium">Public Key Thumbprints</div>
                <div className="bg-slate-950 p-3 rounded-lg border border-slate-800 space-y-2 font-mono text-[11px]">
                  <div>
                    <span className="text-slate-500">Your Key ({currentUser.id}): </span>
                    <span className="text-slate-300">{safetyInfo?.fingerprintA}</span>
                  </div>
                  <div>
                    <span className="text-slate-500">Peer Key ({peerUser.id}): </span>
                    <span className="text-slate-300">{safetyInfo?.fingerprintB}</span>
                  </div>
                </div>
              </div>

              {/* Verification Toggle */}
              <div className="p-4 bg-slate-950 rounded-lg border border-slate-800 flex items-center justify-between">
                <div>
                  <div className="font-semibold text-white text-xs">
                    Mark Identity as Verified
                  </div>
                  <div className="text-slate-400 text-[11px]">
                    Confirms you have verified this safety number with {peerUser.displayName}
                  </div>
                </div>

                <button
                  onClick={handleToggleVerified}
                  className={`px-3.5 py-1.5 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
                    safetyInfo?.isVerified
                      ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40 hover:bg-emerald-500/30'
                      : 'bg-slate-800 text-slate-300 hover:bg-slate-700 border border-slate-700'
                  }`}
                >
                  {safetyInfo?.isVerified ? (
                    <>
                      <ShieldCheck className="w-4 h-4 text-emerald-400" />
                      <span>Verified</span>
                    </>
                  ) : (
                    <>
                      <ShieldAlert className="w-4 h-4 text-slate-400" />
                      <span>Mark Verified</span>
                    </>
                  )}
                </button>
              </div>
            </>
          )}
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-slate-800 flex items-center justify-end">
          <button
            onClick={onClose}
            className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-semibold transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
